"""Procedural sounds: ambience beds and spot effects synthesised from noise and oscillators (numpy only).

Everything here is generated by code, so the factory owns it outright: no licence, no attribution, no download.
Each generator returns float32 audio at 48 kHz, shape (n, 2) (stereo), peak around -6 dBFS; the mixer sets the
final level. Ambience generators return seamless loops (the tail is cross-faded into the head).

Design notes (why it sounds natural rather than "synthy"):
- Noise is coloured in the frequency domain (pink / brown / band-limited), never used raw.
- Every event (tick, drop, crackle, chirp) gets random timing, pitch and level jitter.
- Left and right channels use different random streams, so beds feel wide instead of mono-in-the-middle.
- Rooms get a short synthetic reverb (decaying noise impulse response), outdoor beds stay dry.
"""
from __future__ import annotations

import numpy as np

SR = 48000


# ------------------------------------------------------------------ building blocks
def _rng(seed: int) -> np.random.Generator:
    return np.random.default_rng(seed)


def _n(seconds: float) -> int:
    return max(1, int(round(seconds * SR)))


def shape(x: np.ndarray, gain_fn) -> np.ndarray:
    """Filter by multiplying the spectrum with gain_fn(freqs) (zero-phase, whole-signal FFT)."""
    n = len(x)
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    X *= gain_fn(f)
    return np.fft.irfft(X, n).astype("float32")


def band(lo: float, hi: float, slope: float = 2.0):
    """Smooth band-pass gain curve (soft skirts, `slope` = steepness)."""
    def g(f):
        f = np.maximum(f, 1.0)
        low = 1.0 / (1.0 + (lo / f) ** (2 * slope)) if lo > 0 else 1.0
        high = 1.0 / (1.0 + (f / hi) ** (2 * slope)) if hi < SR / 2 else 1.0
        return low * high
    return g


def colored(n: int, rng, color: str = "pink") -> np.ndarray:
    w = rng.standard_normal(n).astype("float32")
    if color == "white":
        return w
    p = {"pink": 0.5, "brown": 1.0, "blue": -0.5}[color]
    return shape(w, lambda f: 1.0 / np.maximum(f, 20.0) ** p)


def norm(x: np.ndarray, peak: float = 0.5) -> np.ndarray:
    m = float(np.abs(x).max()) if x.size else 0.0
    return (x / m * peak).astype("float32") if m > 0 else x.astype("float32")


def env_exp(n: int, tau: float, attack: float = 0.002) -> np.ndarray:
    t = np.arange(n) / SR
    a = np.minimum(1.0, t / max(attack, 1e-4))
    return (a * np.exp(-t / tau)).astype("float32")


def lfo(n: int, hz: float, rng, depth: float = 0.5, smooth_hz: float | None = None) -> np.ndarray:
    """Random slow modulation in [1-depth, 1] (band-limited noise around `hz`)."""
    w = rng.standard_normal(n).astype("float32")
    top = smooth_hz or hz
    m = shape(w, lambda f: 1.0 / (1.0 + (np.maximum(f, 1e-3) / top) ** 4))
    m = (m - m.min()) / (m.max() - m.min() + 1e-9)
    return (1.0 - depth + depth * m).astype("float32")


def place(track: np.ndarray, sig: np.ndarray, at: int, gain: float = 1.0) -> None:
    if at >= len(track) or at + len(sig) <= 0:
        return
    a, s0 = max(0, at), max(0, -at)
    b = min(len(track), at + len(sig))
    track[a:b] += sig[s0:s0 + (b - a)] * gain


def reverb(x: np.ndarray, t60: float, rng, wet: float = 0.3, pre: float = 0.012) -> np.ndarray:
    n_ir = _n(t60)
    ir = rng.standard_normal(n_ir).astype("float32") * np.exp(-6.9 * np.arange(n_ir) / n_ir).astype("float32")
    ir = shape(ir, band(80, 7000, 1.0))
    ir = np.concatenate([np.zeros(_n(pre), "float32"), ir])
    L = len(x) + len(ir)
    nfft = 1 << (L - 1).bit_length()
    y = np.fft.irfft(np.fft.rfft(x, nfft) * np.fft.rfft(ir, nfft), nfft)[:len(x)]
    y = y / (np.abs(y).max() + 1e-9) * (np.abs(x).max() + 1e-9)
    return ((1 - wet) * x + wet * y).astype("float32")


def fit(x: np.ndarray, n: int) -> np.ndarray:
    """Tile or crop to exactly n samples."""
    if len(x) >= n:
        return x[:n]
    reps = int(np.ceil(n / max(1, len(x))))
    return np.concatenate([x] * reps)[:n]


def stereo(l: np.ndarray, r: np.ndarray | None = None) -> np.ndarray:
    r = l if r is None else r
    n = min(len(l), len(r))
    return np.stack([l[:n], r[:n]], axis=1).astype("float32")


def pan(x: np.ndarray, p: float) -> np.ndarray:
    """Mono → stereo, p in [-1, 1] (equal power)."""
    a = (p + 1) * np.pi / 4
    return np.stack([x * np.cos(a), x * np.sin(a)], axis=1).astype("float32")


def loopify(x: np.ndarray, xfade: float = 1.5) -> np.ndarray:
    """Seamless loop: the last `xfade` seconds are blended into the first ones and cut off."""
    k = min(_n(xfade), len(x) // 3)
    if k < 2:
        return x
    w = np.linspace(0, 1, k, dtype="float32")
    w = np.sin(w * np.pi / 2)
    if x.ndim == 2:
        w = w[:, None]
    head = x[:k] * w + x[-k:] * (1 - w)
    return np.concatenate([head, x[k:-k]]).astype("float32")


def fade(x: np.ndarray, fin: float = 0.005, fout: float = 0.02) -> np.ndarray:
    x = x.copy()
    a, b = min(_n(fin), len(x)), min(_n(fout), len(x))
    ramp_in, ramp_out = np.linspace(0, 1, a, dtype="float32"), np.linspace(1, 0, b, dtype="float32")
    if x.ndim == 2:
        ramp_in, ramp_out = ramp_in[:, None], ramp_out[:, None]
    x[:a] *= ramp_in
    x[len(x) - b:] *= ramp_out
    return x


def tone(freq, seconds: float, phase0: float = 0.0) -> np.ndarray:
    """Sine with a constant or per-sample frequency (array)."""
    n = _n(seconds)
    f = np.full(n, float(freq), "float32") if np.isscalar(freq) else np.asarray(freq, "float32")[:n]
    return np.sin(phase0 + 2 * np.pi * np.cumsum(f) / SR).astype("float32")


def partials(freqs, amps, decays, seconds: float, rng=None) -> np.ndarray:
    """Struck object: sum of decaying sines (bells, metal, glass, wood)."""
    n = _n(seconds)
    t = np.arange(n) / SR
    out = np.zeros(n, "float32")
    for f, a, d in zip(freqs, amps, decays):
        ph = rng.uniform(0, 2 * np.pi) if rng is not None else 0.0
        out += (a * np.sin(2 * np.pi * f * t + ph) * np.exp(-t / d)).astype("float32")
    return out


# ------------------------------------------------------------------ small events (used by beds and spot effects)
def _click(rng, lo=1500, hi=6000, tau=0.006, seconds=0.05) -> np.ndarray:
    x = rng.standard_normal(_n(seconds)).astype("float32") * env_exp(_n(seconds), tau, 0.0005)
    return shape(x, band(lo, hi, 1.5))


def _bubble(rng, f0=None, seconds=0.06, rise=None) -> np.ndarray:
    """Water drop / bubble: a sine whose pitch rises while it decays (Minnaert resonance)."""
    f0 = f0 or rng.uniform(500, 1800)
    rise = rise if rise is not None else rng.uniform(1.3, 2.2)
    n = _n(seconds)
    f = f0 * (1 + (rise - 1) * np.linspace(0, 1, n) ** 0.7)
    return tone(f, seconds) * env_exp(n, seconds / 4, 0.001)


def _rustle(rng, seconds=0.6, lo=1500, hi=9000, density=55.0) -> np.ndarray:
    """Paper / cloth: dense micro-crinkles inside a soft envelope."""
    n = _n(seconds)
    out = np.zeros(n, "float32")
    k = int(seconds * density)
    for _ in range(max(1, k)):
        c = _click(rng, lo, hi, rng.uniform(0.002, 0.012), 0.04)
        place(out, c, int(rng.uniform(0, n)), rng.uniform(0.2, 1.0))
    hiss = shape(rng.standard_normal(n).astype("float32"), band(lo, hi, 1.0)) * 0.15
    e = np.sin(np.linspace(0, np.pi, n)) ** 0.8
    return ((out + hiss) * e).astype("float32")


def _thud(rng, f=85.0, seconds=0.25, tau=0.06) -> np.ndarray:
    n = _n(seconds)
    body = tone(f * np.linspace(1.4, 1.0, n), seconds) * env_exp(n, tau, 0.001)
    knock = shape(rng.standard_normal(n).astype("float32"), band(60, 900, 1.5)) * env_exp(n, 0.012, 0.0005)
    return (body + 0.6 * knock).astype("float32")


def _syllable_env(n: int, rng, rate: float) -> np.ndarray:
    """Speech-like on/off envelope for crowd babble (syllables at `rate` Hz with pauses)."""
    env = np.zeros(n, "float32")
    t = 0
    while t < n:
        if rng.random() < 0.18:                         # pause between phrases
            t += _n(rng.uniform(0.3, 1.2))
            continue
        L = _n(rng.uniform(0.6, 1.4) / rate)
        seg = np.sin(np.linspace(0, np.pi, L)) ** 1.5 * rng.uniform(0.4, 1.0)
        env[t:t + L] = seg[: max(0, min(L, n - t))]
        t += L
    return env


# ------------------------------------------------------------------ ambience beds (seamless loops)
def amb_room(seconds=24.0, seed=1, size="medium") -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    ch = []
    for _ in range(2):
        rum = shape(colored(n, rng, "brown"), band(30, 260, 1.5))
        air = shape(colored(n, rng, "pink"), band(200, 3000, 1.0)) * 0.08
        ch.append(norm(rum + air, 0.2))
    x = stereo(*ch)
    t60 = {"small": 0.35, "medium": 0.8, "large": 2.2}.get(size, 0.8)
    x = stereo(reverb(x[:, 0], t60, rng, 0.25), reverb(x[:, 1], t60, rng, 0.25))
    return loopify(x)


def amb_archive(seconds=24.0, seed=2) -> np.ndarray:
    """Mortimer's archive: quiet room, a slow wall clock, now and then a page or a drawer far away."""
    rng = _rng(seed)
    x = amb_room(seconds + 1.5, seed, "large") * 0.8
    n = len(x)
    tick = 0
    i = 0
    while tick < n:
        c = _click(rng, 1800 + (300 if i % 2 else 0), 5200, 0.004, 0.06) * 0.22
        c += partials([2900 + 200 * (i % 2)], [0.05], [0.03], 0.06)
        place(x[:, 0], c * 0.9, tick)
        place(x[:, 1], c * 0.6, tick + 24)
        tick += _n(1.0 + rng.uniform(-0.004, 0.004))
        i += 1
    for _ in range(int(seconds / 9)):
        r = _rustle(rng, rng.uniform(0.4, 0.8), 1200, 7000, 40) * rng.uniform(0.05, 0.1)
        place(x, pan(r, rng.uniform(-0.8, 0.8)), int(rng.uniform(0, n - _n(1))))
    return loopify(x)


def amb_rain(seconds=24.0, seed=3, heavy: float = 0.5) -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    ch = []
    for _ in range(2):
        bed = shape(colored(n, rng, "pink"), band(500, 9000, 1.0)) * (0.4 + 0.4 * heavy)
        drops = np.zeros(n, "float32")
        for _ in range(int(seconds * (80 + 300 * heavy))):
            place(drops, _bubble(rng, rng.uniform(1500, 5500), 0.02, 1.4), int(rng.uniform(0, n)),
                  rng.uniform(0.02, 0.12))
        ch.append(norm(bed * lfo(n, 0.1, rng, 0.2) + drops, 0.45))
    return loopify(stereo(*ch))


def amb_wind(seconds=24.0, seed=4, strength: float = 0.5) -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    ch = []
    for _ in range(2):
        low = shape(colored(n, rng, "brown"), band(60, 500, 1.5))
        whistle = shape(colored(n, rng, "pink"), band(500, 1600, 2.5)) * 0.35 * strength
        g1, g2 = lfo(n, 0.12, rng, 0.8), lfo(n, 0.25, rng, 0.9)
        ch.append(norm(low * g1 + whistle * g2, 0.45))
    return loopify(stereo(*ch))


def amb_sea(seconds=28.0, seed=5) -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    t = np.arange(n) / SR
    ch = []
    for side in range(2):
        period = rng.uniform(6.5, 9.0)
        swell = (0.5 + 0.5 * np.sin(2 * np.pi * t / period + side * 0.7)) ** 2.2
        surf = shape(colored(n, rng, "pink"), band(150, 6000, 1.0))
        hiss = shape(rng.standard_normal(n).astype("float32"), band(2500, 10000, 1.0)) * 0.25
        rumble = shape(colored(n, rng, "brown"), band(30, 200, 1.5)) * 0.6
        ch.append(norm(surf * (0.25 + swell) + hiss * swell + rumble, 0.45))
    return loopify(stereo(*ch), 3.0)


def amb_fire(seconds=24.0, seed=6) -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    ch = []
    for _ in range(2):
        roar = shape(colored(n, rng, "brown"), band(40, 600, 1.2)) * lfo(n, 0.6, rng, 0.5)
        cr = np.zeros(n, "float32")
        for _ in range(int(seconds * 14)):
            c = _click(rng, 800, 8000, rng.uniform(0.001, 0.006), 0.03)
            place(cr, c, int(rng.uniform(0, n)), min(1.0, rng.pareto(2.5) * 0.15))
        ch.append(norm(norm(roar, 0.3) + norm(cr, 0.35), 0.45))
    return loopify(stereo(*ch))


def amb_night(seconds=24.0, seed=7) -> np.ndarray:
    rng = _rng(seed)
    x = amb_wind(seconds + 1.5, seed, 0.15) * 0.35
    n = len(x)
    for c in range(4):                                     # a few crickets, each with its own pitch and place
        f, p, t = rng.uniform(4200, 5600), rng.uniform(-0.9, 0.9), rng.uniform(0, 0.5)
        while t < seconds:
            chirp = np.concatenate([tone(f, 0.018) * np.hanning(_n(0.018)), np.zeros(_n(0.012), "float32")] * 3)
            place(x, pan(chirp * rng.uniform(0.04, 0.09), p), _n(t))
            t += rng.uniform(0.45, 0.9)
    return loopify(x)


def _bird(rng) -> np.ndarray:
    parts = []
    for _ in range(int(rng.integers(2, 6))):
        d = rng.uniform(0.05, 0.14)
        f0, f1 = rng.uniform(2200, 4200), rng.uniform(2600, 6000)
        f = np.linspace(f0, f1, _n(d)) + 300 * np.sin(np.linspace(0, rng.uniform(4, 12), _n(d)))
        parts += [tone(f, d) * np.hanning(_n(d)), np.zeros(_n(rng.uniform(0.03, 0.09)), "float32")]
    return np.concatenate(parts).astype("float32")


def amb_forest(seconds=24.0, seed=8) -> np.ndarray:
    rng = _rng(seed)
    x = amb_wind(seconds + 1.5, seed, 0.2) * 0.45
    n = len(x)
    leaves = shape(colored(n, rng, "pink"), band(1500, 7000, 1.0)) * lfo(n, 0.3, rng, 0.9) * 0.05
    x += np.stack([leaves, np.roll(leaves, 4800)], axis=1)
    for _ in range(int(seconds / 2.5)):
        place(x, pan(_bird(rng) * rng.uniform(0.03, 0.08), rng.uniform(-0.9, 0.9)), int(rng.uniform(0, n - SR)))
    return loopify(x)


def amb_murmur(seconds=24.0, seed=9, voices: int = 14, room: float = 0.9) -> np.ndarray:
    """Distant crowd babble: many formant-filtered noise 'voices' talking in syllables, blurred by a room."""
    rng = _rng(seed)
    n = _n(seconds + 2)
    L, R = np.zeros(n, "float32"), np.zeros(n, "float32")
    for v in range(voices):
        src = colored(n, rng, "pink")
        f1, f2 = rng.uniform(350, 800), rng.uniform(1000, 2400)
        vox = shape(src, band(f1 * 0.7, f1 * 1.3, 2.0)) + 0.6 * shape(src, band(f2 * 0.8, f2 * 1.2, 2.0))
        vox *= _syllable_env(n, rng, rng.uniform(3.5, 5.5))
        p = rng.uniform(-0.9, 0.9)
        g = rng.uniform(0.4, 1.0)
        a = (p + 1) * np.pi / 4
        L += vox * np.cos(a) * g
        R += vox * np.sin(a) * g
    L, R = reverb(L, room, rng, 0.45), reverb(R, room, rng, 0.45)
    bed = amb_room(seconds + 2, seed + 100, "medium")[:n] * 0.6
    x = stereo(norm(L, 0.4), norm(R, 0.4))[: len(bed)] + bed[: n]
    return loopify(x)


def amb_street_old(seconds=26.0, seed=10) -> np.ndarray:
    """Pre-modern town or market: murmur, footsteps on stone, now and then a cart or horse hooves."""
    rng = _rng(seed)
    x = amb_murmur(seconds + 1.5, seed, 12, 0.6)
    n = len(x)
    for _ in range(int(seconds / 6)):
        t0 = int(rng.uniform(0, n - 3 * SR))
        p = rng.uniform(-0.8, 0.8)
        for k in range(int(rng.integers(6, 12))):            # hooves: clip-clop on cobbles
            c = partials([rng.uniform(700, 1100), rng.uniform(1800, 2600)], [0.5, 0.25], [0.02, 0.012], 0.08, rng)
            c = c * env_exp(len(c), 0.02, 0.0005)
            place(x, pan(c * 0.08, p), t0 + int(k * SR * (0.18 if k % 2 else 0.32)))
    return loopify(x)


def amb_city(seconds=24.0, seed=11) -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    traffic = [norm(shape(colored(n, rng, "brown"), band(40, 900, 1.2)) * lfo(n, 0.08, rng, 0.5), 0.35)
               for _ in range(2)]
    x = stereo(*traffic) + amb_murmur(seconds + 2, seed, 8, 0.5)[:n] * 0.5
    return loopify(x)


def amb_lab(seconds=24.0, seed=12) -> np.ndarray:
    rng = _rng(seed)
    n = _n(seconds + 2)
    t = np.arange(n) / SR
    hum = sum(a * np.sin(2 * np.pi * f * t) for f, a in ((50, 0.10), (100, 0.07), (150, 0.04), (250, 0.02)))
    fan = shape(colored(n, rng, "pink"), band(150, 2500, 1.0)) * 0.6
    x = stereo(norm(hum + fan, 0.3), norm(hum + shape(colored(n, rng, "pink"), band(150, 2500, 1.0)) * 0.6, 0.3))
    for _ in range(int(seconds / 7)):                       # occasional beep / glass tick
        b = tone(rng.choice([880.0, 1320.0, 1760.0]), 0.08) * env_exp(_n(0.08), 0.03) * 0.05
        place(x, pan(b, rng.uniform(-0.7, 0.7)), int(rng.uniform(0, n - SR)))
    return loopify(x)


def amb_gym(seconds=24.0, seed=13) -> np.ndarray:
    rng = _rng(seed)
    x = amb_room(seconds + 1.5, seed, "large") * 0.9 + amb_murmur(seconds + 1.5, seed, 5, 1.2) * 0.25
    n = len(x)
    for _ in range(int(seconds / 4)):                       # plates and dumbbells set down
        c = partials(rng.uniform(300, 900, 4) * [1, 2.7, 5.1, 8.3], [0.5, 0.3, 0.2, 0.1], [0.4, 0.25, 0.15, 0.1],
                     1.0, rng) + _thud(rng, 70, 1.0, 0.05)
        place(x, pan(c * rng.uniform(0.04, 0.09), rng.uniform(-0.8, 0.8)), int(rng.uniform(0, n - SR)))
    return loopify(x)


def amb_hall(seconds=24.0, seed=14) -> np.ndarray:
    """Large stone interior (court, senate, church, museum): long reverb, a few distant voices and steps."""
    room = amb_room(seconds, seed, "large")
    return (room * 0.8 + fit(amb_murmur(seconds, seed, 4, 2.5), len(room)) * 0.25).astype("float32")


def amb_battle(seconds=28.0, seed=15) -> np.ndarray:
    """Distant battle: low rumble, far-off booms, wind. Kept far away on purpose (no gore, no screams)."""
    rng = _rng(seed)
    x = amb_wind(seconds + 1.5, seed, 0.4) * 0.6
    n = len(x)
    for _ in range(int(seconds / 4)):
        b = boom(seed=int(rng.integers(1e6)), far=True)
        place(x, b * rng.uniform(0.2, 0.45), int(rng.uniform(0, n - len(b))))
    return loopify(x)


def amb_stadium(seconds=24.0, seed=16) -> np.ndarray:
    rng = _rng(seed)
    x = amb_murmur(seconds + 1.5, seed, 24, 1.6) * 1.2
    n = len(x)
    swell = shape(colored(n, rng, "pink"), band(300, 4000, 1.2))
    g = lfo(n, 0.06, rng, 1.0) ** 3
    x += np.stack([swell * g, np.roll(swell, 3000) * g], axis=1) * 0.25
    return loopify(x)


def amb_ship(seconds=28.0, seed=17) -> np.ndarray:
    rng = _rng(seed)
    x = amb_sea(seconds + 3, seed) * 0.8
    x = x + fit(amb_wind(seconds + 3, seed, 0.4), len(x)) * 0.3
    n = len(x)
    for _ in range(int(seconds / 5)):                       # wooden creaks
        d = rng.uniform(0.4, 0.9)
        f = np.linspace(rng.uniform(180, 260), rng.uniform(220, 320), _n(d))
        cr = np.sign(tone(f, d)) * np.hanning(_n(d)) * 0.5
        cr = shape(cr.astype("float32"), band(200, 2500, 1.0))
        place(x, pan(cr * 0.05, rng.uniform(-0.6, 0.6)), int(rng.uniform(0, n - SR)))
    return loopify(x)


def amb_desert(seconds=24.0, seed=18) -> np.ndarray:
    rng = _rng(seed)
    x = amb_wind(seconds + 1.5, seed, 0.7)
    n = len(x)
    sand = shape(colored(n, rng, "pink"), band(3000, 11000, 1.0)) * lfo(n, 0.2, rng, 0.9) * 0.08
    return loopify(x + np.stack([sand, np.roll(sand, 2000)], axis=1))


def amb_tavern(seconds=24.0, seed=19) -> np.ndarray:
    """Inside a busy tavern / coffee house / dinner: closer voices, cutlery and cups."""
    rng = _rng(seed)
    x = amb_murmur(seconds + 1.5, seed, 10, 0.5) * 1.1
    n = len(x)
    for _ in range(int(seconds * 0.8)):
        c = partials(rng.uniform(1800, 4200, 3) * [1, 2.3, 3.9], [0.4, 0.2, 0.1], [0.08, 0.05, 0.03], 0.25, rng)
        place(x, pan(c * rng.uniform(0.02, 0.05), rng.uniform(-0.8, 0.8)), int(rng.uniform(0, n - SR)))
    return loopify(x)


def amb_home(seconds=24.0, seed=20) -> np.ndarray:
    """A quiet home: small room, a faint fridge hum, birds far away outside the window."""
    rng = _rng(seed)
    x = amb_room(seconds + 1.5, seed, "small")
    n = len(x)
    t = np.arange(n) / SR
    hum = (0.012 * np.sin(2 * np.pi * 100 * t) + 0.006 * np.sin(2 * np.pi * 200 * t)).astype("float32")
    x += np.stack([hum, hum * 0.8], axis=1)
    for _ in range(int(seconds / 5)):
        b = shape(_bird(rng), band(1500, 6000, 1.0)) * rng.uniform(0.01, 0.025)
        place(x, pan(b, rng.uniform(-0.9, 0.9)), int(rng.uniform(0, n - SR)))
    return loopify(x)


def amb_office(seconds=24.0, seed=21) -> np.ndarray:
    """An office or newsroom: room tone, a few voices, typing on and off, a page now and then."""
    rng = _rng(seed)
    x = amb_room(seconds + 1.5, seed, "medium") + fit(amb_murmur(seconds, seed, 4, 0.8), _n(seconds + 3.5) - _n(1.5)) * 0.3
    n = len(x)
    t = rng.uniform(0, 2)
    while t < seconds:
        keys = int(rng.integers(5, 20))
        tw = typewriter(int(rng.integers(1e6)), keys) * rng.uniform(0.05, 0.12)
        place(x, tw, _n(t))
        t += keys * 0.13 + rng.uniform(2, 6)
    return loopify(x)


