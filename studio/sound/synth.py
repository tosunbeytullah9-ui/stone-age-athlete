def gallop(seed=49, seconds=2.5) -> np.ndarray:
    rng = _rng(seed)
    x = np.zeros(_n(seconds), "float32")
    t = 0.0
    while t < seconds - 0.3:
        for off in (0.0, 0.07, 0.15, 0.22):               # four-beat gallop
            place(x, _thud(rng, rng.uniform(90, 120), 0.15, 0.02), _n(t + off), rng.uniform(0.6, 1.0))
        t += 0.45
    x *= np.linspace(0.2, 1.0, len(x)) * np.linspace(1.0, 0.3, len(x)) * 2
    return pan(fade(norm(x, 0.45)), rng.uniform(-0.5, 0.5))


